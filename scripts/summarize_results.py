"""Collect saved run files into report-ready tables. Nothing is computed that is not on disk.

    python scripts/summarize_results.py --runs outputs/sft outputs/dpo_hh outputs/dpo_ultrafeedback outputs/persona_lora \
        --eval_dir outputs/eval --out_dir outputs/report

Reads ``run_config.json``, ``loop_config.json`` and ``TRAINING_COMPLETE.json`` from each
run, every ``*.summary.json`` written by the judge under ``--eval_dir``, and every
generation JSON under ``<eval_dir>/generations``. Writes ``report_summary.json`` and
``report_tables.md``. Missing inputs appear as "n/a"; no value is ever filled in by hand.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from alignment.io_utils import COMPLETE_MARKER, read_json, write_json  # noqa: E402

REFUSAL_MARKERS = re.compile(
    r"\b(i can(?:'|no)t (?:help|assist|provide)|i cannot|i won't|i am not able to|i'm not able to|"
    r"i'm sorry, but|i am sorry, but|as an ai)\b", re.IGNORECASE)


def _load(path: Path):
    return read_json(path) if path.exists() else None


def fmt(value) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.4g}"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(item) for item in value)
    return str(value)


def pct(value) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def run_row(run_dir: Path) -> dict:
    config = _load(run_dir / "run_config.json") or {}
    loop = _load(run_dir / "loop_config.json") or {}
    done = _load(run_dir / COMPLETE_MARKER) or {}
    is_lora = "lora_r" in config
    batch = config.get("batch_size", config.get("per_device_train_batch_size"))
    accum = config.get("grad_accum_steps", config.get("gradient_accumulation_steps"))
    return {
        "run": run_dir.name,
        "stage": config.get("stage"),
        "completed": bool(done.get("completed")),
        "model": config.get("model_name") or config.get("sft_checkpoint"),
        "trainable": (f"LoRA r={config.get('lora_r')} alpha={config.get('lora_alpha')} dropout={config.get('lora_dropout')} "
                      f"targets={fmt(config.get('lora_target_modules'))}") if is_lora else ("full fine-tuning" if config else None),
        "optimizer": config.get("optimizer", "adamw (TRL default)" if is_lora else None),
        "learning_rate": config.get("learning_rate"),
        "schedule": config.get("schedule", config.get("lr_scheduler_type")),
        "warmup_ratio": config.get("warmup_ratio"),
        "weight_decay": config.get("weight_decay"),
        "max_grad_norm": config.get("max_grad_norm"),
        "batch_size": batch,
        "grad_accum": accum,
        "effective_batch": batch * accum if batch and accum else None,
        "precision": loop.get("precision_effective", config.get("precision", "fp16 on CUDA" if is_lora else None)),
        "max_length": config.get("max_length"),
        "epochs": config.get("epochs", config.get("num_train_epochs")),
        "optimizer_steps": done.get("optimizer_steps", loop.get("total_steps")),
        "seed": config.get("seed"),
        "beta": config.get("beta"),
        "reference": config.get("sft_checkpoint") or ("base model, adapter disabled" if is_lora else None),
        "template": config.get("template", "tokenizer chat template" if is_lora else None),
        "train_rows": loop.get("train_rows", done.get("train_rows")),
        "best_step": done.get("best_step"),
        "best_metrics": done.get("best_metrics"),
        "final_metrics": done.get("final_metrics"),
        "elapsed_minutes": round(done["elapsed_seconds"] / 60, 1) if done.get("elapsed_seconds") else None,
    }


def generation_stats(path: Path) -> dict:
    entries = read_json(path)
    meta = _load(path.with_name(path.stem + ".meta.json")) or {}
    words = [len(entry["output"].split()) for entry in entries]
    count = max(1, len(entries))
    return {
        "file": str(path),
        "generator": entries[0]["generator"] if entries else None,
        "dataset": entries[0]["dataset"] if entries else None,
        "outputs": len(entries),
        "empty_outputs": sum(1 for entry in entries if not entry["output"].strip()),
        "mean_words": sum(words) / count,
        "refusal_marker_rate": sum(1 for entry in entries if REFUSAL_MARKERS.search(entry["output"])) / count,
        "decoding": meta.get("decoding"),
        "template": meta.get("template"),
    }


def tables(summary: dict) -> str:
    lines = ["# Report tables (generated by scripts/summarize_results.py)", "",
             "Every number below was read from a file on disk. `n/a` means the file was not found.", ""]
    lines += ["## Experimental configuration", "",
              "| Run | Trainable parameters | Optimizer | Peak LR | Schedule | Warmup | Weight decay | Clip | Batch x accum = effective "
              "| Precision | Max len | Epochs | Steps | Seed | Beta | Reference checkpoint | Prompt format |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for row in summary["runs"]:
        lines.append(
            f"| {row['run']} | {fmt(row['trainable'])} | {fmt(row['optimizer'])} | {fmt(row['learning_rate'])} | "
            f"{fmt(row['schedule'])} | {fmt(row['warmup_ratio'])} | {fmt(row['weight_decay'])} | {fmt(row['max_grad_norm'])} | "
            f"{fmt(row['batch_size'])} x {fmt(row['grad_accum'])} = {fmt(row['effective_batch'])} | {fmt(row['precision'])} | "
            f"{fmt(row['max_length'])} | {fmt(row['epochs'])} | {fmt(row['optimizer_steps'])} | {fmt(row['seed'])} | "
            f"{fmt(row['beta'])} | {fmt(row['reference'])} | {fmt(row['template'])} |")
    lines += ["", "## Training outcomes", "",
              "| Run | Completed | Train rows | Selected step | Selected-checkpoint metrics | Final metrics | Minutes |",
              "|---|---|---|---|---|---|---|"]
    for row in summary["runs"]:
        def metrics(values):
            if not values:
                return "n/a"
            return "; ".join(f"{key}={fmt(value)}" for key, value in values.items() if isinstance(value, (int, float)))
        lines.append(f"| {row['run']} | {row['completed']} | {fmt(row['train_rows'])} | {fmt(row['best_step'])} | "
                     f"{metrics(row['best_metrics'])} | {metrics(row['final_metrics'])} | {fmt(row['elapsed_minutes'])} |")
    lines += ["", "## Pairwise judgments (candidate vs baseline)", "",
              "Win rates: *excl. ties* = wins / (wins + losses); *ties as half* = (wins + 0.5 ties) / valid judgments. "
              "Unknown and failed pairs are excluded from both and reported separately.", "",
              "| Comparison | Candidate | Baseline | Judge | Pairs | Wins | Losses | Ties | Unknown | Failures | "
              "Win rate excl. ties (95% CI) | Win rate, ties as half | Sign test p | Complete |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for item in summary["judgments"]:
        interval = item.get("wilson_95ci_excluding_ties")
        interval_text = f" ({pct(interval[0])} to {pct(interval[1])})" if interval else ""
        note = " (MOCK: not a result)" if item.get("backend") == "mock" else ""
        lines.append(
            f"| {item.get('comparison')}{note} | {item.get('candidate')} | {item.get('baseline')} | {item.get('judge_model')} | "
            f"{item.get('total_pairs')} | {item.get('candidate_wins')} | {item.get('baseline_wins')} | {item.get('ties')} | "
            f"{item.get('unknown')} | {item.get('failures')} | {pct(item.get('candidate_win_rate_excluding_ties'))}{interval_text} | "
            f"{pct(item.get('candidate_win_rate_ties_as_half'))} | {fmt(item.get('sign_test_p_value'))} | {item.get('complete')} |")
    for item in summary["judgments"]:
        categories = item.get("by_category") or {}
        if len(categories) > 1:
            lines += ["", f"### {item.get('comparison')}: by category", "",
                      "| Category | Pairs | Wins | Losses | Ties | Unknown | Failures | Win rate excl. ties |",
                      "|---|---|---|---|---|---|---|---|"]
            for name, block in categories.items():
                lines.append(f"| {name} | {block['total_pairs']} | {block['candidate_wins']} | {block['baseline_wins']} | "
                             f"{block['ties']} | {block['unknown']} | {block['failures']} | "
                             f"{pct(block['candidate_win_rate_excluding_ties'])} |")
    lines += ["", "## Generation files", "",
              "| File | Generator | Dataset | Outputs | Empty | Mean words | Refusal-marker rate | Max new tokens | Repetition penalty |",
              "|---|---|---|---|---|---|---|---|---|"]
    for item in summary["generations"]:
        decoding = item.get("decoding") or {}
        lines.append(f"| {Path(item['file']).name} | {item['generator']} | {item['dataset']} | {item['outputs']} | "
                     f"{item['empty_outputs']} | {item['mean_words']:.1f} | {pct(item['refusal_marker_rate'])} | "
                     f"{fmt(decoding.get('max_new_tokens'))} | {fmt(decoding.get('repetition_penalty'))} |")
    lines += ["", "The refusal-marker rate is a keyword heuristic for a quick look at refusal behaviour; it is not a judged metric.", ""]
    return "\n".join(lines)


def main(argv=None) -> dict:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", nargs="*", default=["outputs/sft", "outputs/dpo_hh", "outputs/dpo_ultrafeedback",
                                                      "outputs/persona_lora"])
    parser.add_argument("--eval_dir", default="outputs/eval")
    parser.add_argument("--out_dir", default="outputs/report")
    args = parser.parse_args(argv)

    eval_dir = Path(args.eval_dir)
    summary = {
        "runs": [run_row(Path(run)) for run in args.runs if Path(run).exists()],
        "judgments": [read_json(path) for path in sorted(eval_dir.rglob("*.summary.json"))] if eval_dir.exists() else [],
        "generations": [generation_stats(path) for path in sorted((eval_dir / "generations").glob("*.json"))
                        if not path.name.endswith(".meta.json") and not path.name.endswith(".smoke.json")]
        if (eval_dir / "generations").exists() else [],
    }
    out_dir = Path(args.out_dir)
    write_json(out_dir / "report_summary.json", summary)
    (out_dir / "report_tables.md").write_text(tables(summary), encoding="utf-8")
    print(f"[summarize] {len(summary['runs'])} runs, {len(summary['judgments'])} judged comparisons, "
          f"{len(summary['generations'])} generation files -> {out_dir}")
    return summary


if __name__ == "__main__":
    main()
